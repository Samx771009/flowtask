-- Flowtask: ergänzendes Supabase-Schema für die letzte HTML-Version
-- Keine vorhandenen Tabellen oder Daten werden gelöscht.
-- Vor Produktion mit dem vorhandenen Supabase-Schema abgleichen.

create extension if not exists pgcrypto;

create table if not exists public.flowtask_projects (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  color text default '#6558e8',
  created_at timestamptz not null default now()
);

create table if not exists public.flowtask_tasks (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text,
  project text,
  status text not null default 'Auftrag eingegangen',
  priority text default 'Normal',
  due_date date,
  sampling_date date,
  address text,
  email text,
  phone text,
  salutation text,
  first_name text,
  last_name text,
  sample_numbers jsonb not null default '[]'::jsonb,
  attachments jsonb not null default '[]'::jsonb,
  appointment_slot text,
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.flowtask_login_logs (
  id bigint generated by default as identity primary key,
  user_email text,
  logged_in_at timestamptz not null default now(),
  user_agent text
);

create table if not exists public.flowtask_workspace_config (
  id integer primary key default 1 check (id = 1),
  shared_password_hash text,
  updated_at timestamptz not null default now()
);

create or replace function public.flowtask_set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists flowtask_tasks_updated_at on public.flowtask_tasks;
create trigger flowtask_tasks_updated_at
before update on public.flowtask_tasks
for each row execute function public.flowtask_set_updated_at();

alter table public.flowtask_projects enable row level security;
alter table public.flowtask_tasks enable row level security;
alter table public.flowtask_login_logs enable row level security;
alter table public.flowtask_workspace_config enable row level security;

